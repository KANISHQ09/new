// Build auction order: ICON → PLATINUM → GOLD → SILVER → CAPPED → UNCAPPED
// Shuffle within each tier for variety
export const buildAuctionOrder = (shuffle = true) => {
  const tiers = ['ICON', 'PLATINUM', 'GOLD', 'SILVER', 'CAPPED', 'UNCAPPED'];
  const ordered = [];
  for (const tier of tiers) {
    let tierPlayers = IPL_PLAYERS.filter(p => p.tier === tier);
    if (shuffle) {
      tierPlayers = tierPlayers.sort(() => Math.random() - 0.5);
    }
    ordered.push(...tierPlayers);
  }
  return ordered;
};

